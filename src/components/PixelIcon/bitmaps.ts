/** One SVG path for a bitmap: each horizontal run of `#` becomes a rectangle. */
export function toPath(rows: readonly string[]): string {
  let d = ''
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      if (row[x] !== '#') {
        x += 1
        continue
      }
      const start = x
      while (row[x] === '#') x += 1
      d += `M${start} ${y}h${x - start}v1h-${x - start}z`
    }
  })
  return d
}
